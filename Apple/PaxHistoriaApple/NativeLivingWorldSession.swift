import Combine
import Foundation
import OSLog

/// Simulation mode chosen when a new match starts.
enum NativeSimulationMode: String, Codable, CaseIterable, Identifiable {
    case livingWorld // day-based, offline, procedural — no LLM
    case classic // quarterly LLM turns (this session's hash bridge supplies the model)

    var id: String {
        rawValue
    }

    var title: String {
        switch self {
        case .livingWorld: "Living World (day-based)"
        case .classic: "Classic (LLM turns)"
        }
    }

    var subtitle: String {
        switch self {
        case .livingWorld:
            "Victoria-style daily simulation with an AI brain in every country. Runs fully offline."
        case .classic:
            "Quarterly turns generated by your selected AI route, interpreted through world hashes."
        }
    }

    static let storageKey = "NATIVE_SIMULATION_MODE"

    static func current(defaults: UserDefaults = .standard) -> NativeSimulationMode {
        guard let raw = defaults.string(forKey: storageKey), let mode = NativeSimulationMode(rawValue: raw) else {
            return .livingWorld
        }
        return mode
    }
}

/// Owns the Living World playthrough: deterministic day ticking at a
/// player-selected speed, slot persistence (file + backup), and the LLM
/// hash bridge for the optional classic hand-off.
@MainActor
final class LivingWorldSession: ObservableObject {
    @Published private(set) var world: LivingWorldState
    @Published var isRunning = false
    /// Days advanced per timer tick. Vic3-style speed 1...5.
    @Published var speed: Int = 2
    @Published private(set) var lastAutosave: Date?

    let playerCountryCode: String
    private let slot: Int
    private let defaults: UserDefaults
    private let persistenceDirectory: URL
    private var timer: AnyCancellable?
    private var daysSinceSave = 0
    private let logger = Logger(subsystem: "com.gibavargas.SwiftHistoria", category: "LivingWorld")

    static let speedLevels: [Int] = [1, 2, 4, 8, 16] // days per second

    init(playerCountryCode: String, seed: UInt64? = nil, slot: Int = 1, language: NativeGameLanguage? = nil, defaults: UserDefaults = .standard, persistenceDirectory: URL? = nil) {
        self.playerCountryCode = playerCountryCode
        self.slot = slot
        self.defaults = defaults
        let dir = persistenceDirectory ?? FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("SwiftHistoria", isDirectory: true)
            .appendingPathComponent("living-world", isDirectory: true)
        self.persistenceDirectory = dir

        // Language resolution: explicit argument wins, else the campaign
        // store's selected language, else English. A loaded save keeps the
        // language it was generated with.
        let resolvedLanguage = language ?? NativeGameLanguage.normalized(defaults.string(forKey: NativeCampaignStore.selectedLanguageKey))

        if let loaded = Self.load(slot: slot, directory: dir), loaded.playerCountryCode == playerCountryCode {
            world = loaded
            logger.info("Living world resumed day=\(loaded.dayIndex) slot=\(slot)")
        } else {
            let worldSeed = seed ?? Self.seedFromCountry(playerCountryCode)
            world = LivingWorldFactory.makeWorld(seed: worldSeed, playerCode: playerCountryCode)
            world.language = resolvedLanguage
            persist()
            logger.info("Living world generated seed=\(worldSeed) countries=\(self.world.countries.count)")
        }
    }

    static func seedFromCountry(_ code: String) -> UInt64 {
        NativeGameEngine.fnv1aHash("living-world-\(code)")
    }

    var today: LWDate {
        world.today
    }

    var playerCountry: LWCountry? {
        world.countries[playerCountryCode]
    }

    /// Great powers + player, ordered for the sidebar.
    var notableCountries: [LWCountry] {
        world.countries.values
            .sorted { lhs, rhs in
                if lhs.code == playerCountryCode { return true }
                if rhs.code == playerCountryCode { return false }
                return lhs.gdpEstimate > rhs.gdpEstimate
            }
            .prefix(12)
            .map(\.self)
    }

    var recentEvents: [LWEventRecord] {
        world.history.suffix(40).reversed()
    }

    // MARK: Clock

    func togglePlay() {
        isRunning.toggle()
        if isRunning {
            startTimer()
        } else {
            timer?.cancel()
            timer = nil
        }
    }

    var isPaused: Bool {
        !isRunning
    }

    private func startTimer() {
        timer?.cancel()
        let interval = 1.0
        timer = Timer.publish(every: interval, on: .main, in: .common)
            .autoconnect()
            .sink { [weak self] _ in
                self?.advanceOneSecond()
            }
    }

    func advanceOneSecond() {
        guard isRunning else { return }
        let days = Self.speedLevels[max(0, min(speed, Self.speedLevels.count - 1))]
        for _ in 0 ..< days {
            stepDay()
        }
    }

    func stepDay() {
        world = LivingWorldTick.advanceDay(world, playerOrders: nil)
        daysSinceSave += 1
        if daysSinceSave >= 30 {
            persist()
        }
    }

    func pause() {
        isRunning = false
        timer?.cancel()
        timer = nil
    }

    // MARK: Player actions (Vic3-flavored, deterministic)

    func setTaxLevel(_ value: Double) {
        mutatePlayer { $0.taxLevel = min(0.6, max(0.05, value)) }
    }

    func setSpendingLevel(_ value: Double) {
        mutatePlayer { $0.spendingLevel = min(1, max(0.1, value)) }
    }

    func toggleMobilization() {
        mutatePlayer { $0.mobilized.toggle() }
    }

    func build(_ type: LWBuildingType) {
        mutatePlayer { country in
            if let index = country.buildings.firstIndex(where: { $0.type == type }) {
                country.buildings[index].levels += 1
            } else {
                country.buildings.append(LWBuilding(type: type, levels: 1, staffing: 0.5, lastProfit: 0))
            }
            country.treasury -= 8
        }
    }

    func declareWar(on target: String) {
        guard let country = playerCountry, target != playerCountryCode else { return }
        guard !world.wars.contains(where: { $0.attacker == playerCountryCode && $0.defender == target }) else { return }
        let warID = "war-\(playerCountryCode)-\(target)-\(world.dayIndex)"
        world.wars.append(LWWar(
            id: warID,
            attacker: playerCountryCode,
            defender: target,
            startedDay: world.dayIndex,
            warGoal: "Concessions from \(world.countries[target]?.name ?? target)",
            attackerAllies: LivingWorldTick.allies(of: playerCountryCode, world: world),
            defenderAllies: LivingWorldTick.allies(of: target, world: world),
            fronts: [LWFront(id: "\(warID)-front-1", attacker: playerCountryCode, defender: target, progress: 0, intensity: 0.8)],
            exhaustionAttacker: 0,
            exhaustionDefender: 0
        ))
        mutatePlayer { $0.infamy = min(100, $0.infamy + 12) }
        world.adjustRelation(from: playerCountryCode, to: target, delta: -60)
        world.history.append(LWEventRecord(
            id: "war-\(warID)",
            day: world.dayIndex,
            title: "\(country.name) declares war on \(world.countries[target]?.name ?? target)",
            summary: "Our ambassadors have left the capital; the reserves are called up.",
            countryCode: playerCountryCode,
            rarity: .rare,
            severity: 0.9
        ))
        persist()
    }

    func proposeAlliance(with target: String) {
        guard target != playerCountryCode else { return }
        guard !world.pacts.contains(where: { $0.kind == .alliance && (($0.a == playerCountryCode && $0.b == target) || ($0.a == target && $0.b == playerCountryCode)) }) else { return }
        world.pacts.append(LWPact(kind: .alliance, a: playerCountryCode, b: target, sinceDay: world.dayIndex))
        world.adjustRelation(from: playerCountryCode, to: target, delta: 15)
        persist()
    }

    /// Applies an LLM-hash interpretation (classic-mode consequence).
    func applyHashInterpretation(_ interpretation: LivingWorldHashBridge.Interpretation) {
        LivingWorldHashBridge.apply(interpretation, to: &world)
        persist()
    }

    private func mutatePlayer(_ mutation: (inout LWCountry) -> Void) {
        guard var country = world.countries[playerCountryCode] else { return }
        mutation(&country)
        world.countries[playerCountryCode] = country
    }

    // MARK: Vic3-style commentary (main menu + HUD)

    func menuCommentary() -> String {
        guard let player = playerCountry else {
            return LWProse.string(.worldHoldsBreath, language: world.language)
        }
        let rng = LWRNG(worldSeed: world.worldSeed, dayIndex: world.dayIndex)
        return LWBrainFactory.brain(for: player).commentary(world: world, country: player, language: world.language, rng: rng)
    }

    func worldSituationLine() -> String {
        let wars = world.wars.count
        let greatPowers = world.countries.values.filter(\.isGreatPower).count
        let interp = ["wars": "\(wars)", "powers": "\(greatPowers)", "date": world.today.stamp]
        if wars == 1 {
            return LWProse.string(.situationWarSingular, language: world.language, interp)
        }
        if wars > 1 {
            return LWProse.string(.situationWarPlural, language: world.language, interp)
        }
        return LWProse.string(.situationPeace, language: world.language, interp)
    }

    // MARK: Persistence (slot files + backup)

    static let stateFileName = "living-world-state.json"
    static let backupFileName = "living-world-backup.json"

    func persist() {
        daysSinceSave = 0
        lastAutosave = Date()
        let encoder = JSONEncoder()
        guard let primary = try? encoder.encode(world) else {
            logger.error("Living world encode failed")
            return
        }
        let directory = persistenceDirectory
        let slot = slot
        let backupTarget = directory.appendingPathComponent(Self.slotName(Self.backupFileName, slot: slot))
        let primaryTarget = directory.appendingPathComponent(Self.slotName(Self.stateFileName, slot: slot))
        Task.detached(priority: .utility) {
            try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
            // Backup = previous primary, then write new primary (same ordering
            // discipline as the classic store: a crash always leaves a
            // decodable file).
            if let previous = try? Data(contentsOf: primaryTarget) {
                try? previous.write(to: backupTarget, options: [.atomic])
            }
            try? primary.write(to: primaryTarget, options: [.atomic])
        }
    }

    /// Synchronous persistence for critical hand-offs (exit, explicit save,
    /// tests). Blocks until the file is durably written.
    func persistNow() {
        daysSinceSave = 0
        lastAutosave = Date()
        let encoder = JSONEncoder()
        guard let primary = try? encoder.encode(world) else {
            logger.error("Living world encode failed")
            return
        }
        let directory = persistenceDirectory
        let slot = slot
        let backupTarget = directory.appendingPathComponent(Self.slotName(Self.backupFileName, slot: slot))
        let primaryTarget = directory.appendingPathComponent(Self.slotName(Self.stateFileName, slot: slot))
        try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        if let previous = try? Data(contentsOf: primaryTarget) {
            try? previous.write(to: backupTarget, options: [.atomic])
        }
        try? primary.write(to: primaryTarget, options: [.atomic])
    }

    static func load(slot: Int, directory: URL) -> LivingWorldState? {
        let decoder = JSONDecoder()
        let primary = directory.appendingPathComponent(slotName(stateFileName, slot: slot))
        let backup = directory.appendingPathComponent(slotName(backupFileName, slot: slot))
        if let data = try? Data(contentsOf: primary), let state = try? decoder.decode(LivingWorldState.self, from: data) {
            return state
        }
        if let data = try? Data(contentsOf: backup), let state = try? decoder.decode(LivingWorldState.self, from: data) {
            return state
        }
        return nil
    }

    static func slotName(_ base: String, slot: Int) -> String {
        slot <= 1 ? base : base.replacingOccurrences(of: ".json", with: "-slot\(slot).json")
    }

    static func hasSave(slot: Int, directory: URL? = nil) -> Bool {
        let dir = directory ?? FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("SwiftHistoria", isDirectory: true)
            .appendingPathComponent("living-world", isDirectory: true)
        return FileManager.default.fileExists(atPath: dir.appendingPathComponent(slotName(stateFileName, slot: slot)).path)
    }
}

// MARK: - LLM hash bridge (classic mode hand-off)

/// The optional LLM path: the game exports a world prompt the player can run
/// anywhere (e.g. ChatGPT's Python sandbox). The model replies with an
/// 8-nibble world lever hash; the game interprets it deterministically.
enum LivingWorldHashBridge {
    struct Interpretation {
        let summary: String
        let stabilityDelta: Double
        let livingStandardDelta: Double
        let tensionDelta: Double
        let eventSeverity: Double
    }

    /// Builds the paste-able prompt from the current world.
    static func makeWorldPrompt(for world: LivingWorldState) -> String {
        let snapshot: [String: Any] = [
            "worldSeed": String(world.worldSeed),
            "day": world.dayIndex,
            "date": world.today.stamp,
            "player": world.playerCountryCode ?? "",
            "countries": world.countries.values.sorted(by: { $0.code < $1.code }).map { country in
                [
                    "code": country.code,
                    "sol": Double(round(country.standardOfLiving * 10) / 10),
                    "treasury": Double(round(country.treasury)),
                    "solStrata": ["lower": round(country.pops.lower), "middle": round(country.pops.middle)],
                    "atWar": world.wars.contains { $0.attacker == country.code || $0.defender == country.code },
                    "radicals": Double(round(country.radicals * 100) / 100)
                ]
            },
            "wars": world.wars.map { ["id": $0.id, "attacker": $0.attacker, "defender": $0.defender, "progress": Double(round($0.fronts.first?.progress ?? 0))] }
        ]
        guard let data = try? JSONSerialization.data(withJSONObject: snapshot, options: [.sortedKeys]),
              let json = String(data: data, encoding: .utf8)
        else {
            return "{}"
        }
        return """
        You are the world-simulation engine of a geopolitical strategy game.
        Analyze the JSON world snapshot below. Use arithmetic to reason about
        imbalances (deficits, unrest, wars). Then reply with EXACTLY one line:

        WORLDHASH:0x________

        ...where the 8 hexadecimal nibbles encode: nibble1-2 player economy
        (00 worst, FF best), nibble3-4 world tension, nibble5-6 stability of
        the player country, nibble7-8 chance of a major event (00 = none,
        FF = certain). Reply with the hash line only.

        SNAPSHOT:
        \(json)
        """
    }

    /// Interprets a `0x........` world hash deterministically.
    static func interpret(hash: String, world _: LivingWorldState) -> Interpretation? {
        let cleaned = hash
            .trimmingCharacters(in: .whitespacesAndNewlines)
            .replacingOccurrences(of: " ", with: "")
        guard cleaned.hasPrefix("WORLDHASH:0x") || cleaned.hasPrefix("0x") else { return nil }
        let hexPortion = cleaned.hasPrefix("WORLDHASH:0x") ? String(cleaned.dropFirst("WORLDHASH:0x".count)) : String(cleaned.dropFirst(2))
        guard hexPortion.count >= 8, hexPortion.allSatisfy(\.isHexDigit) else { return nil }
        let nibbles = hexPortion.prefix(8).map { $0.hexDigitValue ?? 0 }

        func nibblePair(_ high: Int, _ low: Int) -> Double {
            Double(high * 16 + low) / 255.0 // 0..1
        }

        let economy = nibblePair(nibbles[0], nibbles[1])
        let tension = nibblePair(nibbles[2], nibbles[3])
        let stability = nibblePair(nibbles[4], nibbles[5])
        let eventRoll = nibblePair(nibbles[6], nibbles[7])

        return Interpretation(
            summary: String(
                format: "Economy %.0f%% · Tension %.0f%% · Stability %.0f%% · Event %.0f%%",
                economy * 100, tension * 100, stability * 100, eventRoll * 100
            ),
            stabilityDelta: (stability - 0.5) * 10,
            livingStandardDelta: (economy - 0.5) * 2,
            tensionDelta: (tension - 0.5) * 10,
            eventSeverity: eventRoll
        )
    }

    /// Applies an interpretation to the world (classic-mode consequence).
    static func apply(_ interpretation: Interpretation, to world: inout LivingWorldState) {
        guard let code = world.playerCountryCode, var player = world.countries[code] else { return }
        player.standardOfLiving = max(4, player.standardOfLiving + interpretation.livingStandardDelta)
        player.radicals = min(1, max(0, player.radicals - interpretation.stabilityDelta / 200))
        world.countries[code] = player
        world.history.append(LWEventRecord(
            id: "hash-\(world.dayIndex)-\(world.worldSeed)",
            day: world.dayIndex,
            title: "World assessment received",
            summary: interpretation.summary,
            countryCode: code,
            rarity: .weekly,
            severity: interpretation.eventSeverity
        ))
    }
}
